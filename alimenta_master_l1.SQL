MERGE INTO
  `a2a-labrrclab-prd.L1.DAR_MARGINI_MASTER` AS mar
USING
  (

SELECT DISTINCT
  COD_OFFERTA as COD_OFFER,
  MAX(CONSIP) AS CONSIP,
  MIN(LOTTO) AS LOTTO
FROM
(
SELECT
  DISTINCT 
  ass.CODICE_CONTRATTO_SFA AS COD_OFFERTA,
  pag.FK_ACCOUNT,
  IF(SETTORE LIKE 'CON__L%', CONCAT('CONSIP',RIGHT(LEFT(SETTORE,5),2)), IF(LEFT(SETTORE,7) = 'CON2880','CONSIP23',null)) AS CONSIP,
  IF(SETTORE LIKE 'CON__L%', RIGHT(LEFT(SETTORE,8),2), IF(LEFT(SETTORE,7) = 'CON2880',RIGHT(LEFT(SETTORE,10),2),null)) AS LOTTO
FROM
  `a2a-dataplatform-prd.DP_LAB.MetodiPagamento` pag
LEFT JOIN
  `a2a-dataplatform-prd.DP_LAB.Asset` ass
ON
  pag.PK_METODI_PAGAMENTO = ass.FK_METODI_PAGAMENTO
WHERE
  SETTORE LIKE 'CON%'
  AND pag.expiry_ts IS NULL
  AND ass.expiry_ts IS NULL
  --AND CAST(RIGHT(LEFT(SETTORE,5),2) AS int64) >=19
  AND ass.CODICE_CONTRATTO_SFA is not null
  
UNION DISTINCT

SELECT
  DISTINCT 
  CASE WHEN pra.CODICE_OFFERTA is null THEN pra.CODICE_OPPORTUNITY ELSE pra.CODICE_OFFERTA END AS COD_OFFERTA,
  pag.FK_ACCOUNT,
  IF(SETTORE LIKE 'CON__L%', CONCAT('CONSIP',RIGHT(LEFT(SETTORE,5),2)), IF(LEFT(SETTORE,7) = 'CON2880','CONSIP23',null)) AS CONSIP,
  IF(SETTORE LIKE 'CON__L%', RIGHT(LEFT(SETTORE,8),2), IF(LEFT(SETTORE,7) = 'CON2880',RIGHT(LEFT(SETTORE,10),2),null)) AS LOTTO
FROM
  `a2a-dataplatform-prd.DP_LAB.MetodiPagamento` pag
LEFT JOIN
  `a2a-labrrclab-prd.L0.DAR_PraticheCompletaFiltrata_tabella` pra
ON
  pag.PK_METODI_PAGAMENTO = pra.FK_METODI_PAGAMENTO
WHERE
  SETTORE LIKE 'CON%'
  AND pag.expiry_ts IS NULL
  AND pra.expiry_ts IS NULL
  --AND CAST(RIGHT(LEFT(SETTORE,5),2) AS int64) >=19
  AND CASE WHEN pra.CODICE_OFFERTA is null THEN pra.CODICE_OPPORTUNITY ELSE pra.CODICE_OFFERTA END is not null  
)
WHERE (CONSIP = "CONSIP19" AND LOTTO =  "12") OR (CONSIP = "CONSIP20" AND (LOTTO =  "12" OR LOTTO = "02" OR LOTTO = "08" OR LOTTO = "09")) OR (CONSIP = "CONSIP21" AND (LOTTO =  "12" OR LOTTO = "02" OR LOTTO = "03" OR LOTTO = "06" OR LOTTO = "08" OR LOTTO = "09")) OR (CONSIP = "CONSIP22" AND (LOTTO =  "02" OR LOTTO = "03" OR LOTTO = "06" OR LOTTO = "07" OR LOTTO = "08" OR LOTTO = "09" OR LOTTO = "10" OR LOTTO = "12" OR LOTTO = "13" OR LOTTO = "16"  OR LOTTO = "17")) OR (CONSIP = "CONSIP23" AND (LOTTO =  "12" OR LOTTO = "18"))
GROUP BY COD_OFFERTA
  ) AS cons

ON
  mar.COD_OFFERTA = cons.COD_OFFER
  WHEN MATCHED
  THEN
UPDATE
SET
  mar.CONSIP_CONVENZIONE = COALESCE(cons.CONSIP, IF(mar.NOTE LIKE "CONSIP%", mar.NOTE, null)),
  mar.CONSIP_LOTTO = COALESCE(cons.LOTTO, null);





MERGE INTO
  `a2a-labrrclab-prd.L1.DAR_MARGINI_MASTER` AS mar
USING
  ( SELECT ID_OFFERTA, ID_DETTAGLIO, NOTE
    FROM `a2a-labrrclab-prd.L1.DAR_MARGINI_MASTER`
    WHERE NOTE is not null) AS mar2
ON
  mar.ID_OFFERTA = mar2.ID_OFFERTA AND mar.ID_DETTAGLIO = mar2.ID_DETTAGLIO
  WHEN MATCHED
  THEN
UPDATE
SET
  mar.CONSIP_CONVENZIONE = COALESCE(mar.CONSIP_CONVENZIONE, IF(mar2.NOTE LIKE "CONSIP%", mar2.NOTE, null));






